"""Generate explicit boundary DTOs and shared TS models from reviewed, versioned field definitions."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generate():
 models=json.loads((ROOT/'contracts/view-models.json').read_text(encoding='utf-8'))
 java=['package com.sunshine.yunji.content.shared.contract;','import java.util.List;','import java.math.BigDecimal;','import io.swagger.v3.oas.annotations.media.Schema;','/** Generated by scripts/generate_view_models.py; edit contracts/view-models.json. */','public final class Views {',' private Views() {}']
 ts=['// Generated from contracts/view-models.json. IDs are strings; nullable database fields stay explicit.']
 for name,fields in models.items():
  args=[];ts.append('export interface '+name+' {')
  for field in fields:
   annotation='@Schema(nullable='+str(field['nullable']).lower()+', requiredMode=Schema.RequiredMode.'+('NOT_REQUIRED' if field['nullable'] else 'REQUIRED')
   if field.get('format'):annotation+=', format="'+field['format']+'"'
   if field.get('enum'):annotation+=', allowableValues={'+','.join('"'+v+'"' for v in field['enum'])+'}'
   annotation+=') '
   args.append(annotation+field['type']+' '+field['name'])
   typ=field['type'];t={'String':'string','Integer':'number','Long':'number','Boolean':'boolean','BigDecimal':'number'}.get(typ,typ)
   if typ.startswith('List<'):t=typ[5:-1]+'[]';t=t.replace('String[]','string[]')
   if field.get('enum'):t=' | '.join("'"+v+"'" for v in field['enum'])
   ts.append(' '+field['name']+': '+t+(' | null' if field['nullable'] else '')+';')
  java.append(' public record '+name+'('+', '.join(args)+') {}');ts.append('}')
 java.append('}')
 out=ROOT/'backend/agri-modules/yunji-content/src/main/java/com/sunshine/yunji/content/shared/contract';out.mkdir(parents=True,exist_ok=True)
 (out/'Views.java').write_text('\n'.join(java)+'\n',encoding='utf-8')
 for app in ['admin','client']:
  target=ROOT/'apps'/app/'src/types/models.ts';target.parent.mkdir(parents=True,exist_ok=True);target.write_text('\n'.join(ts)+'\n',encoding='utf-8')
 print('Generated',len(models),'boundary models for Java and both frontends')

if __name__=='__main__':generate()
